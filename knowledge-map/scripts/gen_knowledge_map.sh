#!/usr/bin/env bash
# Derive the orientation map from checked inputs; publish only a complete render.
# --print-map-path prints the runtime absolute destination (not persisted data).
set -uo pipefail
refuse(){ printf 'KNOWLEDGE-MAP: REFUSED — %s\n' "$1" >&2; exit 2; }
ROOT="$(git rev-parse --show-toplevel)" || refuse 'repository root unavailable'
MAP="$ROOT/KNOWLEDGE_MAP.md"
if [ "${1:-}" = '--print-map-path' ]; then
  printf '%s\n' "$MAP" || refuse 'destination output failed'
  exit 0
fi
cd "$ROOT" || refuse 'repository root unavailable'
[ -f knowledge-map/subsystems.md ] || refuse 'curated source missing'
mkdir -p "$ROOT/target/tmp" || refuse 'scratch directory unavailable'
tmp="$(mktemp -d "$ROOT/target/tmp/knowledge-map.XXXXXX")" || refuse 'scratch allocation failed'
trap 'rm -rf -- "$tmp"' EXIT

cat > "$tmp/map" <<'HDR' || refuse 'header output failed'
# KNOWLEDGE_MAP — derived orientation map

<!-- DERIVED — DO NOT EDIT. Regenerated by knowledge-map/scripts/gen_knowledge_map.sh and
     staged by the pre-commit hook, so drift is structurally impossible. Edit the SOURCES:
     knowledge-map/subsystems.md, docs/tasks/, docs/decisions/. -->

## Key subsystems
HDR
sed '/^<!--/,/-->/d' knowledge-map/subsystems.md >> "$tmp/map" || refuse 'curated source read failed'

map_directory(){
  local directory="$1" f b excluded skip found=0
  shift
  [ -d "$directory" ] || refuse "inventory directory missing: $directory"
  local files=()
  shopt -s nullglob
  files=("$directory"/*.md)
  : > "$tmp/sorted" || refuse 'inventory output failed'
  if [ "${#files[@]}" -gt 0 ]; then
    for f in "${files[@]}"; do
      [ -f "$f" ] && [ ! -L "$f" ] || refuse "nonregular inventory member: $f"
      case "$f" in *$'\n'*|*$'\r'*) refuse 'newline in inventory member';; esac
    done
    ls -1 -- "${files[@]}" > "$tmp/unsorted" || refuse "inventory discovery failed: $directory"
    LC_ALL=C sort "$tmp/unsorted" > "$tmp/sorted" || refuse "inventory sort failed: $directory"
  fi
  while IFS= read -r f; do
    b="${f##*/}"; skip=0
    for excluded in "$@"; do [ "$b" != "$excluded" ] || skip=1; done
    [ "$skip" -eq 0 ] || continue
    printf -- '- [`%s`](%s/%s)\n' "$b" "$directory" "$b" >> "$tmp/map" || refuse 'member output failed'
    found=1
  done < "$tmp/sorted"
  if [ "$found" -eq 0 ]; then
    printf '%s\n' '- _none yet_' >> "$tmp/map" || refuse 'empty inventory output failed'
  fi
}
printf '\n## Task-tree files\n\n' >> "$tmp/map" || refuse 'task heading output failed'
map_directory docs/tasks TEMPLATE.md
printf '\n## Decision records\n\n' >> "$tmp/map" || refuse 'decision heading output failed'
map_directory docs/decisions INDEX.md TEMPLATE.md
cat "$tmp/map" || refuse 'complete map output failed'
