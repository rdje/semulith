def main(argv):
    import argparse
    from riscv_asm import AsmError
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='compare without writing')
    parser.add_argument('--check-owned', action='store_true', help='check the explicit historical author corpus')
    parser.add_argument('--parcels', action='store_true', help='execute exact byte images under C/ILEN=32')
    parser.add_argument('--steps', type=int, help='explicit boundary budget for --parcels (1..10000)')
    parser.add_argument('--encoding', type=Path, default=ENCODING)
    parser.add_argument('guests', nargs='*', type=Path)
    args = parser.parse_args(argv[1:])
    if args.check_owned and args.guests:
        parser.error('--check-owned selects its corpus; do not also pass guests')
    if args.parcels and (args.steps is None or args.check_owned):
        parser.error('--parcels requires --steps and cannot select the historical --check-owned corpus')
    if not args.parcels and args.steps is not None:
        parser.error('--steps requires --parcels')
    paths = ([REPO / 'profiles/rv64gc-lab-v0/guests' / (n + '.s') for n in OWNED_GUESTS]
             if args.check_owned else args.guests)
    if not paths:
        parser.error('pass guest sources or --check-owned')
    try:
        asm = Assembler(args.encoding)
        results = [(p, *(run_parcel_guest(p, asm, args.steps) if args.parcels else run_guest(p, asm)))
                   for p in paths]
    except (Refusal, AsmError, OSError) as exc:
        print(f'derive_rv64gc_expectations: REFUSED — {exc}', file=sys.stderr)
        return 2
    drift = []
    for path, text, steps in results:
        out = path.with_suffix('.expected.sexp')
        if args.check or args.check_owned:
            if not out.is_file() or out.read_text() != text:
                drift.append(path.stem)
        else:
            out.write_text(text)
            print(f'derive_rv64gc_expectations: wrote {out.name} ({steps} steps)')
    if drift:
        print('derive_rv64gc_expectations: DRIFT — ' + ', '.join(drift), file=sys.stderr)
        return 1
    if args.check or args.check_owned:
        print(f'derive_rv64gc_expectations: {len(paths)} guest(s) byte-identical; no records written')
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
