class Hart:
    """The spec-side hart: registers, memory, the CSRs the corpus touches, the
    reservation (the declared policy), and the Sv39 walk (the pinned 10 steps, Svade)."""

    def __init__(self):
        self.x = [0] * 32
        self.f = [0] * 32        # the f-file, FLEN = 64; the laboratory reset 0 (state.sexp)
        self.pc = ENTRY
        self.mode = M
        self.mem = {}
        self.csr = {"mtvec": 0, "mepc": 0, "mcause": 0, "mtval": 0, "mscratch": 0,
                    "mstatus": 0xA00000000, "medeleg": 0, "satp": 0, "sepc": 0, "scause": 0,
                    "stval": 0, "sscratch": 0, "mcounteren": 0, "scounteren": 0,
                    "mie": 0, "mip": 0, "mideleg": 0, "sie": 0, "sip": 0, "stimecmp": 0,
                    "fflags": 0, "frm": 0}   # fcsr is the composed VIEW, never storage
        self.time = 0            # the declared virtual-time domain (one tick per step)
        self.instret = 0         # the GENUINE retirement count (never for a trapped,
                                 # delivered or halted step — the engine's !frame.trapped)
        self.trapped = False     # set by any delivery this step (the instret discipline)
        self.waiting = False     # the hart wait state (decision 4), cold-ACTIVE at reset
        self.reservation = None   # (pa, width_bytes)
        self.log = []

    def read(self, addr, n):
        return sum(self.mem.get(addr + i, 0) << (8 * i) for i in range(n))

    def write(self, addr, n, v):
        for i in range(n):
            self.mem[addr + i] = (v >> (8 * i)) & 0xFF

    def in_region(self, addr, n):
        return ENTRY <= addr and addr + n <= ENTRY + REGION

    def refused(self, kind, addr, n):
        """A declared refusal region answers this request (P4-SYSTEM.8 slice c)."""
        return any(k == kind and addr < b + s and b < addr + n
                   for k, b, s in getattr(self, "refusals", ()))

    # ---- trap delivery (RVP-MACHINE §2.1.1.6.1, §2.1.1.8, §2.1.1.14-16) ----------------
    def deliver(self, cause, tval):
        self.trapped = True     # a trap-delivering step retires nothing (instret)
        from_mode = self.mode
        deleg = (self.csr["medeleg"] >> cause) & 1
        to_s = deleg and from_mode <= S
        if to_s:
            self.csr["sepc"] = self.pc & ~1
            self.csr["scause"] = cause
            self.csr["stval"] = tval
            mstatus = self.csr["mstatus"]
            mstatus = (mstatus & ~(1 << 5)) | (((mstatus >> 1) & 1) << 5)  # SPIE <- SIE
            mstatus &= ~(1 << 1)                                          # SIE <- 0
            mstatus = (mstatus & ~(1 << 8)) | ((1 if from_mode == S else 0) << 8)  # SPP
            self.csr["mstatus"] = mstatus
            self.pc = self.csr["mtvec"] & ~0  # stvec shares the programmed vector here
            self.pc = self.stvec()
        else:
            self.csr["mepc"] = self.pc & ~1
            self.csr["mcause"] = cause
            self.csr["mtval"] = tval
            mstatus = self.csr["mstatus"]
            mstatus = (mstatus & ~(1 << 7)) | (((mstatus >> 3) & 1) << 7)  # MPIE <- MIE
            mstatus &= ~(1 << 3)                                           # MIE <- 0
            mstatus = (mstatus & ~(0b11 << 11)) | (from_mode << 11)        # MPP
            self.csr["mstatus"] = mstatus
            self.pc = self.csr["mtvec"] & ~0b11
        self.mode = S if to_s else M

    def stvec(self):
        # the corpus programs ONE vector address through mtvec and reads it as stvec's
        # too (the laboratory guest convention — stvec is a distinct CSR the guests that
        # route to S program separately; see sv39-deleg's template)
        return self.csr.get("stvec", 0) & ~0b11

    def mip_value(self, which):
        """mip/sip with the live STIP overlay (time >= stimecmp — slice a's ticking
        domain; the SSIP/SEIP bits are storage)."""
        base = self.csr[which]
        stip = 1 if self.time >= self.csr["stimecmp"] else 0
        return (base & ~(1 << 5)) | (stip << 5)

    def wake_pending(self):
        """The WFI wake evaluation (decision 4, RVP-MACHINE §2.1.3.3): a locally-enabled
        pending interrupt at any privilege level, regardless of the global enables and
        of mideleg — exactly mip & mie != 0, mip with the live STIP overlay (the timer's
        arrival during the halt is the acceptance's wake source)."""
        return (self.mip_value("mip") & self.csr["mie"]) != 0

    def pending(self):
        """The (a)(b)(c) taken-rule at the step head (decision 3): the fixed priority
        walk MEI MSI MTI SEI SSI STI; the M-source bits read 0 in this platform."""
        for cause in (11, 3, 7, 9, 1, 5):
            bit = 1 << cause
            if not (self.mip_value("mip") & bit and self.csr["mie"] & bit):
                continue
            if self.csr["mideleg"] & bit:
                if self.mode == 3:
                    continue                     # the delegation mask: never in M
                if self.mode == 1 and ((self.csr["mstatus"] >> 1) & 1) == 0:
                    continue                     # S with SIE clear
                return (cause, True)
            else:
                if self.mode == 3 and ((self.csr["mstatus"] >> 3) & 1) == 0:
                    continue                     # M with MIE clear
                return (cause, False)
        return None

    def deliver_interrupt(self, cause, to_s):
        """Interrupt-caused delivery (decision 3): the Interrupt bit (63), xepc the
        un-fetched pc, the xPIE/xIE/xPP stack, the vector HONORING MODE."""
        self.trapped = True
        origin = self.mode
        code = cause | (1 << 63)
        if to_s:
            self.csr["sepc"] = self.pc & ~1
            self.csr["scause"] = code
            self.csr["stval"] = 0
            m = self.csr["mstatus"]
            sie = (m >> 1) & 1
            m = (m & ~(1 << 5)) | (sie << 5)
            m &= ~(1 << 1)
            m = (m & ~(1 << 8)) | ((1 if origin == 1 else 0) << 8)
            self.csr["mstatus"] = m
            self.mode = 1
            vec = self.csr.get("stvec", 0)
        else:
            self.csr["mepc"] = self.pc & ~1
            self.csr["mcause"] = code
            self.csr["mtval"] = 0
            m = self.csr["mstatus"]
            mie = (m >> 3) & 1
            m = (m & ~(1 << 7)) | (mie << 7)
            m &= ~(1 << 3)
            m = (m & ~(0b11 << 11)) | (origin << 11)
            self.csr["mstatus"] = m
            self.mode = 3
            vec = self.csr["mtvec"]
        base = vec & ~0b11
        self.pc = base + 4 * cause if vec & 0b11 == 1 else base

    # ---- the pinned 10-step Sv39 walk (RVP-SUPERVISOR §11.1.3.2, §11.1.4.1; Svade) ----
    def walk(self, va, kind):
        """kind in {'fetch','load','store','atomic'} -> ('pa', pa) or ('fault', cause)."""
        if kind not in ('fetch', 'load', 'store', 'atomic'):
            raise Refusal(f"walk kind {kind!r}: not in the declared access vocabulary")
        mode = self.mode
        if kind != 'fetch' and (self.csr['mstatus'] >> 17) & 1:
            mode = (self.csr['mstatus'] >> 11) & 3  # MPRV: data uses MPP, fetch never does
        satp_mode = self.csr['satp'] >> 60
        if mode == M or satp_mode == 0:
            return ("pa", va)
        if mode not in (0, S) or satp_mode != 8:
            raise Refusal(f"walk mode {mode}/satp.MODE {satp_mode}: outside the selected profile")
        cause = {"fetch": 12, "load": 13, "store": 15, "atomic": 15}[kind]
        expected_upper = (1 << 25) - 1 if (va >> 38) & 1 else 0
        if va >> 39 != expected_upper:
            return ("fault", cause)
        base = (self.csr["satp"] & ((1 << 44) - 1)) << 12
        vpn = [(va >> (12 + 9 * i)) & 0x1FF for i in range(3)]
        for level in (2, 1, 0):
            pte_addr = base + vpn[level] * 8
            self.log.append(('walk', pte_addr, 8))
            # an implicit walk read the environment refuses (outside the region, or a declared
            # walk refusal) is the ORIGINAL access's access fault (the engine's mapping;
            # P4-SYSTEM.8 slice c — the model read zeros there before, a page fault)
            if not self.in_region(pte_addr, 8) or self.refused("walk", pte_addr, 8):
                return ("fault", {"fetch": 1, "load": 5, "store": 7, "atomic": 7}[kind])
            pte = self.read(pte_addr, 8)
            v, r, w, x = pte & 1, (pte >> 1) & 1, (pte >> 2) & 1, (pte >> 3) & 1
            u, a, d = (pte >> 4) & 1, (pte >> 6) & 1, (pte >> 7) & 1
            # Svnapot/Svpbmt are absent; every PTE bit 63:54 must be zero.
            if not v or (not r and w) or pte >> 54:
                return ("fault", cause)
            if r or x:  # a leaf
                ppn2 = (pte >> 28) & ((1 << 26) - 1)
                ppn1 = (pte >> 19) & ((1 << 9) - 1)
                ppn0 = (pte >> 10) & ((1 << 9) - 1)
                if level == 2 and (ppn1 or ppn0):
                    return ("fault", cause)
                if level == 1 and ppn0:
                    return ("fault", cause)
                # RVP-SUPERVISOR 11.1.1.1.2 and translation step 6: SUM only
                # permits S data accesses to U pages; MXR also permits X-only loads.
                if mode == 0 and not u:
                    return ("fault", cause)
                if mode == S and u and (kind == "fetch" or not (self.csr["mstatus"] >> 18) & 1):
                    return ("fault", cause)
                if kind == "fetch" and not x:
                    return ("fault", cause)
                if kind == "load" and not (r or (x and (self.csr["mstatus"] >> 19) & 1)):
                    return ("fault", cause)
                if kind == "store" and not w:
                    return ("fault", cause)
                if kind == "atomic" and not (r and w):
                    return ("fault", cause)
                if not a or (kind in ("store", "atomic") and not d):
                    return ("fault", cause)  # Svade: page fault, never an update
                pa = (ppn2 << 30) | ((ppn1 if level <= 1 else (va >> 21) & 0x1FF) << 21) \
                    | ((ppn0 if level == 0 else (va >> 12) & 0x1FF) << 12) | (va & 0xFFF)
                return ("pa", pa)
            if pte & 0xd0:  # non-leaf U/A/D are reserved (RSW/G remain allowed)
                return ("fault", cause)
            if level == 0:
                return ("fault", cause)  # the pointer cannot descend below the final level
            base = ((pte >> 10) & ((1 << 44) - 1)) << 12
        raise AssertionError("three-level walk failed to produce a result")

    def fetch_instruction(self):
        """Fetch one instruction under C/ILEN=32; no retirement/time tick here.

        Returns ('insn', original_bits, length_bytes) or ('fault', cause, tval).
        A fault delivers with the instruction start as EPC and the failing parcel's
        VA as tval. Each necessary parcel walks before its exact two-byte request;
        log records actual boundary attempts, including refused requests. Memory in
        the declared region defaults to zero, even beyond the assembled payload.
        """
        def parcel(va):
            translated = self.walk(va, 'fetch')
            if translated[0] == 'fault':
                return ('fault', translated[1], va)
            pa = translated[1]
            self.log.append(('fetch', pa, 2))
            if pa & 1:
                return ('fault', 0, va)
            if not self.in_region(pa, 2) or self.refused('fetch', pa, 2):
                return ('fault', 1, va)
            return ('parcel', self.read(pa, 2))

        pc = self.pc
        low = parcel(pc)
        if low[0] == 'fault':
            self.deliver(low[1], low[2])
            return low
        if low[1] & 3 != 3:
            return ('insn', low[1], 2)
        high = parcel(u(pc + 2))
        if high[0] == 'fault':
            self.deliver(high[1], high[2])
            return high
        return ('insn', low[1] | (high[1] << 16), 4)


