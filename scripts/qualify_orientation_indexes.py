#!/usr/bin/env python3
"""Replay LC0034's finite orientation/index readers in owned on-volume copies.

Exit0 means measurement complete, including recorded source defects. Select
--require-clean to fail1 on wrong public verdicts. Failed qualification refuses2.
The immutable fixture is not a full graph, adoption or processor qualification.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys

import collect_containment_graph as C

ROOT = C.ROOT
SOURCE = '50a102b984fd7c8733f284505e68c383ce158dfa'
GEN = 'knowledge-map/scripts/gen_knowledge_map.sh'
GUARD = 'knowledge-map/scripts/check_knowledge_map.sh'
MEMORY = 'scripts/check_memory_architecture.sh'
MAP = 'KNOWLEDGE_MAP.md'
CURATED = 'knowledge-map/subsystems.md'
require = C.require


def roster(body: bytes, prefix='') -> list[str]:
    """Read actual Markdown table destinations, not arbitrary filename mentions."""
    rows = []
    for line in body.decode('utf-8').splitlines():
        if not line.startswith('| ['):
            continue
        match = re.match(r'^\| \[[^\]]+\]\(([^)]+)\) \|', line)
        require(match is not None, 'unsupported index table row')
        target = match.group(1)
        C.Q.relative_path(target)
        require(target.endswith('.md'), 'non-Markdown index destination')
        rows.append(prefix + target)
    require(len(rows) == len(set(rows)), 'duplicate index destination')
    return rows


def inventory(bodies: dict[str, bytes]) -> dict:
    def direct(directory, exclusions):
        return sorted(n for n in bodies if n.startswith(directory + '/')
                      and '/' not in n[len(directory) + 1:]
                      and n.endswith('.md') and Path(n).name not in exclusions)
    tasks = direct('docs/tasks', {'TEMPLATE.md'})
    decisions = direct('docs/decisions', {'INDEX.md', 'TEMPLATE.md'})
    knowledge = direct('docs/knowledge', {'INDEX.md', 'TEMPLATE.md'})
    listed = {
        'tasks': roster(bodies['docs/TASK_TREE.md'], 'docs/')
                 + roster(bodies['docs/TASK_TREE_CLOSED.md'], 'docs/'),
        'decisions': roster(bodies['docs/decisions/INDEX.md'], 'docs/decisions/'),
        'knowledge': roster(bodies['docs/knowledge/INDEX.md'], 'docs/knowledge/'),
    }
    expected = {'tasks': tasks, 'decisions': decisions, 'knowledge': knowledge}
    for family, names in expected.items():
        require(len(listed[family]) == len(names) and set(listed[family]) == set(names),
                'complete independent index membership: ' + family)
    return {'members': expected, 'listed_order': listed,
            'excluded': sorted(n for n in bodies if n.endswith('.md') and
                               n.startswith(('docs/tasks/', 'docs/decisions/', 'docs/knowledge/'))
                               and n not in set(tasks + decisions + knowledge))}


def render(bodies: dict[str, bytes], members: dict) -> bytes:
    # Fixed public heading contract; independently expand the owned filename census.
    header = '''# KNOWLEDGE_MAP — derived orientation map

<!-- DERIVED — DO NOT EDIT. Regenerated by knowledge-map/scripts/gen_knowledge_map.sh and
     staged by the pre-commit hook, so drift is structurally impossible. Edit the SOURCES:
     knowledge-map/subsystems.md, docs/tasks/, docs/decisions/. -->

## Key subsystems
'''
    curated, hidden = [], False
    for line in bodies[CURATED].decode('utf-8').splitlines(keepends=True):
        if line.startswith('<!--'):
            hidden = True
        if not hidden:
            curated.append(line)
        if hidden and '-->' in line:
            hidden = False
    require(not hidden, 'unclosed curated comment')
    text = header + ''.join(curated)
    for title, family in [('Task-tree files', 'tasks'), ('Decision records', 'decisions')]:
        text += '\n## ' + title + '\n\n'
        names = members[family]
        text += ''.join('- [`' + Path(n).name + '`](' + n + ')\n' for n in names)
        if not names:
            text += '- _none yet_\n'
    return text.encode()


def reconcile(actual: bytes, expected: bytes) -> None:
    require(actual == expected, 'complete independent map bytes/membership differ')


def execute(command, fixture, output, label, fault=None):
    tools = output / 'tools'
    if tools.exists():
        shutil.rmtree(tools)
    tools.mkdir()
    trace = output / (label + '.faults')
    env = dict(os.environ)
    env.update(GIT_DIR=str(ROOT / '.git'), GIT_WORK_TREE=str(fixture),
               GIT_NO_LAZY_FETCH='1', TMPDIR=str(output / 'tmp'),
               ORIENTATION_LAUNCH_LOG=str(output / 'failed-generator.calls'))
    if fault:
        tool, status = fault
        script = ('#!/bin/bash\nprintf \'%s\\n\' ' + shlex.quote(tool)
                  + ' >> ' + shlex.quote(str(trace)) + '\nexit ' + str(status) + '\n')
        (tools / tool).write_text(script)
        (tools / tool).chmod(0o755)
        env['PATH'] = str(tools) + os.pathsep + env['PATH']
    result = subprocess.run(command, cwd=fixture, env=env, capture_output=True,
                            check=False, timeout=60)
    (output / (label + '.stdout')).write_bytes(result.stdout)
    (output / (label + '.stderr')).write_bytes(result.stderr)
    calls = trace.read_text().splitlines() if trace.exists() else []
    if fault:
        expected_calls = {'sed': 1, 'ls': 2, 'sort': 2, 'grep': 59}[fault[0]]
        require(calls == [fault[0]] * expected_calls, 'actual tool fault count differs')
    return result, calls


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', required=True)
    parser.add_argument('--addition', action='append', default=[])
    parser.add_argument('--working-code', action='store_true')
    parser.add_argument('--require-clean', action='store_true')
    args = parser.parse_args()
    os.environ['GIT_NO_LAZY_FETCH'] = '1'
    try:
        C.Q.relative_path(args.output)
        require(args.output.startswith('target/'), 'on-volume target output required')
        output = C.U.source_path(ROOT, args.output)
        require(not output.exists(), 'fresh output required')
        before = C.working_snapshot(args.addition)
        source = C.source_census(SOURCE)
        require(len(source['members']) == 1448, 'immutable source population')
        rows = C.Q.tree_rows(C.Q.git('ls-tree', '-rz', '--full-tree', SOURCE))
        selected = {n: r for n, r in rows.items() if r[0] != '160000' and
                    (n.startswith(('docs/tasks/', 'docs/decisions/', 'docs/knowledge/'))
                     or n in {GEN, GUARD, MEMORY, MAP, CURATED, 'MEMORY.md', 'README.md',
                              'CLAUDE.md', 'docs/TASK_TREE.md', 'docs/TASK_TREE_CLOSED.md'})}
        wire = C.Q.checked_output(subprocess.run(['git', '--no-optional-locks', '-C', str(ROOT),
            'cat-file', '--batch'], input=b''.join(r[2].encode() + b'\n' for r in selected.values()),
            capture_output=True, check=False))
        bodies = C.blob_contents(selected, wire)
        if args.working_code:
            for name in [GEN, GUARD, MEMORY]:
                pin = C.file_identity(name)
                require(pin['mode'] == (0o755 if selected[name][0] == '100755' else 0o644),
                        'working code mode differs')
                bodies[name] = (ROOT / name).read_bytes()
        population = inventory(bodies)
        expected = render(bodies, population['members'])
        reconcile(bodies[MAP], expected)
        output.mkdir(parents=True)
        (output / 'tmp').mkdir()
        fixture = output / 'source'

        def reset():
            if fixture.exists():
                shutil.rmtree(fixture)
            for name, body in bodies.items():
                path = fixture / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(body)
                path.chmod(0o755 if selected[name][0] == '100755' else 0o644)

        observations = []

        def observe(case, interface, status, fault=None):
            result, calls = execute(['bash', {'generator': GEN, 'guard': GUARD,
                'memory': MEMORY}[interface]], fixture, output, case + '-' + interface, fault)
            observations.append({'case': case, 'interface': interface,
                'expected_returncode': status, 'returncode': result.returncode,
                'stdout_bytes': len(result.stdout), 'stdout_sha256': C.digest(result.stdout),
                'stderr_sha256': C.digest(result.stderr), 'fault_calls': calls})
            return result

        reset()
        result = observe('baseline', 'generator', 0)
        reconcile(result.stdout, expected)
        observe('baseline', 'guard', 0)
        observe('baseline', 'memory', 0)
        (fixture / MAP).write_bytes(expected + b'\n')
        observe('map-drift', 'guard', 1)
        for case, fault in [('missing-curated', None), ('sed-failed', ('sed', 42)),
                            ('ls-failed', ('ls', 42)), ('sort-failed', ('sort', 42))]:
            reset()
            if case == 'missing-curated':
                (fixture / CURATED).unlink()
            observe(case, 'generator', 2, fault)
            observe(case, 'guard', 2, fault)
        reset()
        # A failed actual generator emits exact bytes: only its exit status is false.
        launch_log = output / 'failed-generator.calls'
        failed = ('#!/bin/bash\nif [ "${1:-}" = --print-map-path ]; then printf "%s\\n" "$PWD/'
                  + MAP + '"; exit 0; fi\nprintf \'failed-main\\n\' >> '
                  + '"$ORIENTATION_LAUNCH_LOG"\ncat ' + MAP + '\nexit 42\n')
        (fixture / GEN).write_text(failed)
        observe('generator-failed-after-exact-output', 'guard', 2)
        require(launch_log.read_text().splitlines() == ['failed-main'],
                'actual failed generator must execute exactly once')
        decision = population['members']['decisions'][0]
        index = 'docs/decisions/INDEX.md'
        row = next(line + b'\n' for line in bodies[index].splitlines()
                   if b'](' + Path(decision).name.encode() + b')' in line)
        reset()
        (fixture / index).unlink()
        observe('missing-decision-index', 'memory', 1)
        reset()
        (fixture / index).write_bytes(bodies[index].replace(row, b'', 1))
        observe('missing-decision-row', 'memory', 1)
        (fixture / index).write_bytes((fixture / index).read_bytes() + b'<!-- '
                                     + Path(decision).name.encode() + b' -->\n')
        observe('comment-only-decision', 'memory', 1)
        reset()
        observe('grep-failed', 'memory', 2, ('grep', 42))

        omissions = []
        for family in ['tasks', 'decisions', 'curated']:
            reset()
            original = bodies[GEN]
            if family == 'curated':
                old = b"  sed '/^<!--/,/-->/d' knowledge-map/subsystems.md"
                new = b'  : # LC0034 actual curated read omission'
            else:
                directory = 'tasks' if family == 'tasks' else 'decisions'
                name = Path(population['members'][family][0]).name
                old = ('  echo "- [\\`$b\\`](docs/' + directory + '/$b)"; found=1').encode()
                new = ('  if [ "$b" != ' + shlex.quote(name) + ' ]; then '
                       + old.decode().strip() + '; fi').encode()
            require(original.count(old) == 1, 'unique actual map omission seam ' + family)
            (fixture / GEN).write_bytes(original.replace(old, new, 1))
            result, _ = execute(['bash', GEN], fixture, output, 'omit-' + family)
            require(result.returncode == 0, 'omission did not execute successfully')
            try:
                reconcile(result.stdout, expected)
            except ValueError:
                omissions.append({'family': family, 'generator_returncode': 0,
                    'independent_qualification_returncode': 2,
                    'source_old': old.decode(), 'source_new': new.decode(),
                    'mutated_generator_sha256': C.digest(original.replace(old, new, 1)),
                    'output_sha256': C.digest(result.stdout)})
            else:
                raise ValueError('actual map omission was not discriminated')
        controls = []
        for family in ['tasks', 'decisions', 'knowledge']:
            changed = dict(bodies)
            path = {'tasks': 'docs/TASK_TREE_CLOSED.md', 'decisions': index,
                    'knowledge': 'docs/knowledge/INDEX.md'}[family]
            lines = changed[path].splitlines(keepends=True)
            victim = next(line for line in lines if line.startswith(b'| ['))
            changed[path] = changed[path].replace(victim, b'', 1)
            try:
                inventory(changed)
            except ValueError:
                controls.append({'family': family, 'returncode': 2})
            else:
                raise ValueError('independent roster omission accepted')
        require(before == C.working_snapshot(args.addition), 'actual source/index/modes changed')
        defects = [r for r in observations if r['returncode'] != r['expected_returncode']]
        record = {'source': SOURCE, 'source_members': len(source['members']),
            'source_tree_sha256': source['tree_sha256'],
            'mode': 'optimized' if sys.flags.optimize else 'normal',
            'code_mode': 'working' if args.working_code else 'immutable',
            'inputs': [{**r, 'bytes': len(bodies[n]), 'sha256': C.digest(bodies[n])}
                       for n, r in ((r['path'], r) for r in source['members']) if n in bodies],
            'population': population, 'map_bytes': len(expected), 'map_sha256': C.digest(expected),
            'observations': observations, 'source_defects': len(defects),
            'actual_omissions': omissions, 'roster_controls': controls,
            'failed_generator': {'body': failed, 'sha256': C.digest(failed.encode()),
                                 'actual_main_calls': 1}}
        (output / 'result.json').write_text(json.dumps(record, indent=2) + '\n')
        print(json.dumps({k: record[k] for k in ['source', 'mode', 'code_mode', 'source_defects']}
                         | {'inputs': len(bodies), 'observations': len(observations),
                            'populations': {k: len(v) for k, v in population['members'].items()}}))
        return 1 if args.require_clean and defects else 0
    except (ValueError, OSError, UnicodeError, subprocess.SubprocessError) as exc:
        print('qualify_orientation_indexes: REFUSED — ' + str(exc), file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
